import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {dependency,browserOptions} from './dependencies.mjs';
const {chromium}=dependency('playwright');
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const qa=path.join(root,'tools','qa');fs.mkdirSync(qa,{recursive:true});
const browser=await chromium.launch(browserOptions());
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const requests=[];page.on('request',r=>{if(/^https?:/.test(r.url()))requests.push(r.url());});
await page.goto(pathToFileURL(path.join(root,'index.html')).href);
await page.waitForFunction(()=>[...document.querySelectorAll('figure img')].every(i=>i.complete&&i.naturalWidth>0));
const structure=await page.evaluate(()=>({images:document.querySelectorAll('figure img').length,chapters:document.querySelectorAll('.chapter').length,codeBlocks:document.querySelectorAll('pre').length,brokenAnchors:[...document.querySelectorAll('a[href^="#"]')].map(a=>a.hash.slice(1)).filter(id=>!document.getElementById(id)),overflow:document.documentElement.scrollWidth>innerWidth}));
if(structure.images!==12||structure.chapters!==12||structure.brokenAnchors.length||structure.overflow)throw new Error(JSON.stringify(structure));
await page.screenshot({path:path.join(qa,'desktop.png')});
await page.locator('figure img').first().click();
if(!await page.locator('dialog').evaluate(el=>el.open))throw new Error('Zoom failed');
await page.locator('#close-zoom').click();
await page.locator('#cn').fill('4');
let capacity=await page.locator('#r3').innerText();
if(!capacity.startsWith('1209.60'))throw new Error('Storage calculation failed: '+capacity);
await page.locator('#cw').fill('3840');await page.locator('#ch').fill('2160');
const raw=await page.locator('#r0').innerText(),lane=await page.locator('#r1').innerText(),memory=await page.locator('#r2').innerText();
if(!raw.startsWith('2488.32')||!lane.startsWith('622.08')||!memory.startsWith('1492.99'))throw new Error('Bandwidth calculation failed');
await page.locator('#calculator').scrollIntoViewIfNeeded();
await page.screenshot({path:path.join(qa,'calculator.png')});
await page.locator('#cw').fill('');
if(await page.locator('#r0').innerText()!=='—')throw new Error('Invalid input not handled');
await page.locator('#cw').fill('1920');await page.locator('#ch').fill('1080');await page.locator('#cn').fill('1');
await page.setViewportSize({width:390,height:844});
await page.goto(pathToFileURL(path.join(root,'index.html')).href+'?mobileqa=1');
await page.evaluate(()=>{document.activeElement.blur();document.documentElement.style.scrollBehavior='auto';scrollTo({top:0,behavior:'instant'});});
await page.waitForFunction(()=>scrollY===0);
await page.screenshot({path:path.join(qa,'mobile.png')});
if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw new Error('Mobile overflow');
await page.locator('#mobile-menu').click();
if(!await page.locator('aside').isVisible())throw new Error('Mobile menu failed');
await page.locator('nav a[href="#chapter-3"]').click();
if(await page.locator('aside').isVisible())throw new Error('Mobile menu did not close');
await page.screenshot({path:path.join(qa,'mobile-code.png')});
await page.setViewportSize({width:1120,height:620});
for(const name of fs.readdirSync(path.join(root,'assets')).filter(f=>f.endsWith('.svg')).sort()){
 await page.goto(pathToFileURL(path.join(root,'assets',name)).href);
 await page.screenshot({path:path.join(root,'assets',name.replace('.svg','.png'))});
}
await page.route('http://**',r=>r.abort());await page.route('https://**',r=>r.abort());
await page.goto(pathToFileURL(path.join(root,'examples','player.html')).href);
await page.locator('#host').fill('bad/path');await page.locator('button[type=submit]').click();
if(!(await page.locator('#status').innerText()).includes('请输入'))throw new Error('Player validation failed');
await page.locator('#host').fill('192.168.1.50');await page.locator('button[type=submit]').click();
if(await page.locator('#screen').getAttribute('src')!=='http://192.168.1.50:8889/cam0')throw new Error('Player URL failed');
await page.locator('#stop').click();
if(await page.locator('#screen').getAttribute('src')!==null)throw new Error('Player disconnect failed');
await page.screenshot({path:path.join(qa,'player.png')});
await browser.close();
if(errors.length)throw new Error(errors.join('\n'));
fs.writeFileSync(path.join(qa,'results.json'),JSON.stringify({structure,errors,offlineBookRequests:requests.filter(x=>!x.includes('192.168.1.50')),calculator:{raw,lane,memory,capacity},checks:['desktop and mobile layout','12 embedded images','chapter anchors','image zoom','mobile navigation','calculator valid and invalid inputs','player URL validation and disconnect']},null,2));
console.log('Browser QA passed. 12 SVGs rendered to PNG; screenshots and report saved.');
